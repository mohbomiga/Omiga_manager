create table if not exists public.omiga_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  kind text not null check (kind in ('repair','sale','expense','purchase')),
  description text not null,
  amount numeric(12,2) not null default 0 check (amount >= 0),
  cost numeric(12,2) not null default 0 check (cost >= 0),
  category text,
  entry_date date not null default current_date,
  notes text,
  created_at timestamptz not null default now()
);

alter table public.omiga_entries enable row level security;

create policy "Users can view their own entries"
on public.omiga_entries for select
using (auth.uid() = user_id);

create policy "Users can add their own entries"
on public.omiga_entries for insert
with check (auth.uid() = user_id);

create policy "Users can delete their own entries"
on public.omiga_entries for delete
using (auth.uid() = user_id);

create policy "Users can update their own entries"
on public.omiga_entries for update
using (auth.uid() = user_id)
with check (auth.uid() = user_id);
